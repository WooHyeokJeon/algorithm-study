import copy

# 1. 참조 복사 (=는 같은 객체를 가리킴)
# b = a는 복사가 아니라서 b를 바꾸면 a도 바뀜
a = [1, 2, 3]
b = a
b.append(5)
print('a: ', a)   # a:  [1, 2, 3, 5]
print('b: ', b)   # b:  [1, 2, 3, 5]

# 2. 슬라이싱 복사 (a[:])
# 1차원 리스트는 a[:]로 복사하면 독립된 복사본이 생김
a = [1, 2, 3]
b = a[:]
b.append(5)
print('a: ', a)   # a:  [1, 2, 3]
print('b: ', b)   # b:  [1, 2, 3, 5]

# 3. 2차원 리스트 슬라이싱 복사
# 바깥 리스트만 복사되고 안쪽 리스트는 공유됨
a = [[1, 2], [3, 4]]
b = a[:]
b.append(5)
print('a: ', a)   # a:  [[1, 2], [3, 4]]
print('b: ', b)   # b:  [[1, 2], [3, 4], 5]

# 4. 2차원 리스트 슬라이싱 복사 후 안쪽 리스트 수정
# 안쪽 리스트 [3, 4]를 공유하므로 a[1]을 바꾸면 b도 바뀜
a = [[1, 2], [3, 4]]
b = a[:]
a[1].append(5)
print('a: ', a)   # a:  [[1, 2], [3, 4, 5]]
print('b: ', b)   # b:  [[1, 2], [3, 4, 5]]

# 5. deepcopy로 완전히 독립된 복사
# 안쪽 리스트까지 모두 복사하므로 a를 바꿔도 b는 영향 없음
a = [[1, 2], [3, 4]]
b = copy.deepcopy(a)
a[1].append(5)
print('a: ', a)   # a:  [[1, 2], [3, 4, 5]]
print('b: ', b)   # b:  [[1, 2], [3, 4]]